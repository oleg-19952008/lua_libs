M.W = 5
M.H = 7
M.ADVANCE = 6 -- ширина символа + 1 колонка межбуквенного интервала

--- Нарисовать текст попиксельно в буфер.
-- bufSet(x, y, r, g, b) — колбэк записи пикселя (уже с проверкой границ).
-- text — только ASCII; регистр сохраняется, кириллица пропускается.
function M.draw(bufSet, x, y, text, rgb)
    local r, g, b = rgb[1], rgb[2], rgb[3]
    local cx = x
    for i = 1, #text do
        local ch = text:sub(i, i)
        local glyph = GLYPHS[ch] or GLYPHS[ch:lower()]
        if glyph then
            for row = 1, 7 do
                local bits = glyph[row]
                if bits and bits ~= 0 then
                    for col = 0, 4 do
                        if testBit(bits, 4 - col) then
                            bufSet(cx + col, y + row - 1, r, g, b)
                        end
                    end
                end
            end
        end
        cx = cx + M.ADVANCE
    end
    return cx -- позиция после последнего символа
end

--- Измерить ширину текста в колонках.
function M.width(text)
    if #text == 0 then return 0 end
    return #text * M.ADVANCE - 1
end

return M
