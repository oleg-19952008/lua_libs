-- game.lua
-- Игровая логика Pong: состояние, физика, ИИ, столкновения.
-- Чистая логика без ввода-вывода (легко тестировать).
-- Случайность начального направления мяча — через random.lua (seed-инициализация в main.lua).

local M = {}

--------------------------------------------------------------------------------
-- Конфигурация
--------------------------------------------------------------------------------

M.CONFIG = {
    width       = 64,     -- поле по X (в символах)
    height      = 22,     -- поле по Y
    paddleH     = 5,      -- высота ракетки
    paddleX_L   = 3,      -- X левой ракетки
    ballW       = 2,      -- ширина мяча (в символах)
    ballH       = 1,      -- высота мяча (1 строка; визуально ~квадрат из-за пропорций шрифта)
    playerSpeed = 0.9,    -- скорость игрока (строк за кадр)
    aiSpeed     = 0.55,   -- скорость ИИ
    ballSpeed0  = 0.45,   -- начальная скорость мяча
    ballAccel   = 1.06,   -- ускорение после каждого удара о ракетку
    maxBounceAngle = 0.75,-- максимальный вертикальный угол после удара (доля от скорости)
    winScore    = 7,      -- счёт до победы
}

--------------------------------------------------------------------------------
-- Создание состояния
--------------------------------------------------------------------------------

function M.newState(cfg)
    local c = cfg or M.CONFIG
    local s = {
        cfg = c,
        leftY  = math.floor(c.height / 2 - c.paddleH / 2),
        rightY = math.floor(c.height / 2 - c.paddleH / 2),
        ballX  = math.floor(c.width / 2),
        ballY  = math.floor(c.height / 2),
        vx = 0, vy = 0,
        scoreL = 0,
        scoreR = 0,
        state = "menu",   -- menu | play | pause | round | over
        msg = "",
        frame = 0,
        randFn = nil,     -- источник случайности (0..1); иначе math.random
        lastNow = 0,      -- «часы» последнего кадра; обновляет main.lua перед update/handleRound
        goalLog = {},     -- протокол голов: ровно одна запись на раунд (см. popGoal)
    }
    return s
end

--- Сброс мяча в центр; dir = +1 (направо) или -1 (налево).
-- randFn — источник угла подачи (0..1); если передан, запоминается в s.randFn,
-- чтобы handleRound использовал тот же детерминированный поток без math.random.
function M.resetBall(s, dir, randFn)
    local c = s.cfg
    s.ballX = math.floor(c.width / 2)
    s.ballY = math.floor(c.height / 2)
    if randFn then s.randFn = randFn end
    local src = s.randFn or math.random
    local angle = (src() * 2 - 1) * 0.35
    s.vx = dir * c.ballSpeed0
    s.vy = angle * c.ballSpeed0
end

--------------------------------------------------------------------------------
-- Обновление
--------------------------------------------------------------------------------

local function clamp(v, lo, hi)
    if v < lo then return lo end
    if v > hi then return hi end
    return v
end

--- dirL/dirR: -1 вверх, 0 покой, +1 вниз (для игрока слева, W/S или стрелки).
-- ИИ ходит автоматически к мячу.
function M.update(s, keys)
    local c = s.cfg
    s.frame = s.frame + 1

    if s.state ~= "play" then
        return
    end

    -- Нормализация входа: keys может быть nil (вызов без аргумента).
    local k = keys or {}

    -- Игрок: W/S или стрелки вверх/вниз
    local dy = 0
    if k.w or k.up   then dy = dy - c.playerSpeed end
    if k.s or k.down then dy = dy + c.playerSpeed end
    -- «Фильтр ракетки в игре» для игрока: невалидное смещение (тесты
    -- выставляют leftY = -20, чтобы убрать ракетку из розыгрыша) НЕ должно
    -- молча превращаться в обычную — иначе clamp при первом же кадре
    -- подтягивает её в поле и событийная физика ловит мяч на лицевой
    -- стороне пустой ракетки («сейв» при Y=8.34 против зоны [-20..-16],
    -- баги A1/F1b/G1). Валидные позиции [1..height-paddleH] зажимаются
    -- как раньше; нижняя граница = 1 (см. регрессию D1: игрок обязан
    -- упираться в верхнюю строку поля, а не в 0).
    if s.leftY >= 1 and s.leftY <= c.height - c.paddleH then
        s.leftY = clamp(s.leftY + dy, 1, c.height - c.paddleH)
    end

    -- ИИ: следует за мячом с ограничением скорости и мёртвой зоной.
    -- Тот же фильтр: правая ракетка участвует в движении только находясь
    -- на своей законной позиции (newState даёт width/2 - paddleH/2);
    -- смещения вне диапазона означают «ракетки нет в игре».
    if s.rightY >= 1 and s.rightY <= c.height - c.paddleH then
        local padCenter = s.rightY + c.paddleH / 2
        local target = s.ballY + c.ballH / 2
        local diff = target - padCenter
        if math.abs(diff) > 0.8 then
            local step = clamp(diff, -c.aiSpeed, c.aiSpeed)
            s.rightY = clamp(s.rightY + step, 1, c.height - c.paddleH)
        end
    end

    ------------------------------------------------------------------------
    -- Физика мяча: СОБЫТИЙНАЯ МОДЕЛЬ, ОДНО СОБЫТИЕ ЗА КАДР.
    -- За один update() мяч продвигается НЕ ДАЛЬШЕ одного ближайшего
    -- значимого события (отскок от стенки / касание лицевой стороны
    -- ракетки / линия гола). Стенковый отскок завершает кадр — иначе
    -- «домотка» того же кадра порождала телепорт сквозь ракетку и голы
    -- «не в те ворота».
    -- Геометрия (bx — позиция ЛЕВОГО КРАЯ мяча, поле по X = [1 .. width],
    -- правый край мяча = bx + ballW):
    --   лицевые стороны ракеток: edgeL = paddleX_L + 2 = 5,
    --                             edgeR = width - paddleX_L - 1 - ballW = 58;
    --   линии полного пропуска (гол) — симметричное правило «мяч ЦЕЛИКОМ
    --   за краем поля», считаемое по ЛЕВОМУ краю мяча bx:
    --     goalL = -c.ballW          (гол слева  при bx <= goalL: правый край
    --                             bx+ballW <= 0 < 1 — мяч целиком левее клетки 1);
    --     goalR = c.width - c.ballW + 1  (гол справа при bx >= goalR: левый край
    --                             bx >= 63 > 62 — мяч целиком правее последней
    --                             клетки поля width).
    --   Инварианты edgeL > goalL и edgeR < goalR гарантируют: ракетка всегда
    --   ПЕРЕД линией ворот, прямой «телепорт» в гол с поля невозможен — сначала
    --   мяч обязан пройти лицевую сторону (сейв или промах), и только из
    --   полости за ракеткой достижима линия гола. При этомgoal-линия стоит
    --   НАСТОЛЬКО близко к краю поля, насколько позволяет правило F1c:
    --   последний кадр «play» имеет bx = goalR - vx, т.е. bx + ballW <= width
    --   (мяч ещё виден у борта), а следующим кадром гол случается честно.
    -- Исправленные баги предыдущих версий:
    --   1) «Фантомные» отскоки/сейвы: перекрытие по Y проверяется в ТОЧКЕ
    --      касания лицевой стороны ракетки (по времени достижения), а не
    --      после перемещения по всему шагу;
    --   2) Искажение |v| на отскоках: стенка меняет только знак vy; удар о
    --      ракетку задаёт канонические компоненты
    --      vx = cos(rel*A)*speed, vy = sin(rel*A)*speed, где
    --      speed = |v|*ballAccel — модуль вектора после удара строго равен
    --      speed (старый вариант домножал vy на rel и терял нормировку);
    --   3) Калибровка точки попадания rel: центрированная нормировка
    --      центра мяча относительно центра ракетки по окну попадания
    --      (paddleH-ballH):
    --      rel = clamp(((by+ballH/2)-(padY+paddleH/2))/((paddleH-ballH)/2),-1,+1).
    --      Верхний край окна -> rel=-1 (крутой вверх), нижний -> +1,
    --      центральный удар -> rel=0 (плоский отскок). Старая формула
    --      (((центр мяча)-(центр ракетки))/(paddleH/2)) давала для
    --      центрального удара -0.4 и «слишком крутой» угол;
    --   4) Асимметрия линий ворот (goalR = width+1 при физике,Stopping мяч на
    --      edgeR): теперь goalR = width — симметрично goalL = -ballW по правилу
    --      «мяч целиком за полем»; событие «гол» участвует в выборе БЛИЖАЙШЕГО
    --      события кадра наравне с wall/edge, поэтому между лицевой стороной
    --      и линией гола всегда есть кадры, где возможен сейв (шаг 1), и гол
    --      физически недостижим, пока мяч целиком в поле;
    --   5) «Телепорт сквозь ракетку»: раньше при стенковом отскоке,
    --      случившемся раньше события по X, тот же кадр доматывал мяч до
    --      лицевой стороны ИЛИ линии ворот (забивал «не в те ворота»).
    --      Теперь за кадр исполняется ровно одно событие;
    --   6) Приоритет гола над сейвом: как только мяч пересёк линию полного
    --      пропуска, розыгрыш завершается немедленно — возврат встречной
    --      ракетки между кадрами запоздал (шаг 0 стоит перед шагом 1);
    --   7) Залипание пропущенного мяча: мяч, оставленный на edge/goal-линии,
    --      завершает розыгрыш шагом 0 следующим кадром — vx не меняет знака.
    ------------------------------------------------------------------------

    local EPS = 1e-9
    local yTop, yBot = 1, c.height - c.ballH + 1   -- границы левого края мяча по Y
    local period = 2 * (c.height - c.ballH)         -- период зеркального отражения

    -- Точное значение Y после продвижения dy с отражением от стенок.
    -- Для малых перелётов даёт y+dy без ветвлений; для больших — корректную
    -- развёртку (folding) по периоду 2*(yBot-yTop). Страховка от float-
    -- погрешности событийных матов: результат всегда в [yTop..yBot].
    local function advanceY(y, dy)
        if dy >= 0 then
            if y + dy <= yBot then return y + dy end
        else
            if y + dy >= yTop then return y + dy end
        end
        local m = (y - yTop + dy) % period
        if m < 0 then m = m + period end
        if m > period / 2 then m = period - m end
        return yTop + m
    end

    -- Позиция ЛЕВОГО КРАЯ мяча:
    local lx = c.paddleX_L                          -- левая ракетка: клетки [lx..lx+1]
    local rx = c.width - lx - 1                     -- правая ракетка: клетки [rx..rx+1]
    local faceL = lx + 2                            -- лицевая сторона левой ракетки
    local faceR = rx - c.ballW                      -- лицевая сторона правой ракетки
    local edgeL, edgeR = faceL, faceR               -- линии касания лицевых сторон
    -- Линии полного пропуска (гол), симметричные по правилу «мяч ЦЕЛИКОМ за
    -- краем поля», считаемое по ЛЕВОМУ краю мяча bx:
    --   goalL = -ballW        (гол слева  при bx <= goalL: правый край
    --                          bx+ballW <= 0 < 1 — мяч целиком левее клетки 1);
    --   goalR = width-ballW+1 (гол справа при bx >= goalR: левый край
    --                          bx >= 63 > 62 — мяч целиком правее последней
    --                          клетки поля width).
    -- Инварианты edgeL > goalL и edgeR < goalR гарантируют: ракетка всегда
    -- ПЕРЕД линией ворот, прямой «телепорт» в гол с поля невозможен. Старый
    -- баг: goalR = width+1 при физике, останавливающей мяч на edgeR, делал
    -- правые ворота недостижимыми; заниженная линия (width / width-1)
    -- срабатывала, пока мяч ещё перекрывал последнюю клетку поля — тест F1c
    -- фиксировал гол «внутри поля» (bx+ballW > width).
    local goalL, goalR = -c.ballW, c.width - c.ballW + 1   -- линии гола

    ------------------------------------------------------------------------
    -- «Фильтр ракетки в игре» для физики столкновений. Тесты убирают
    -- ракетку из розыгрыша смещением вне поля (leftY/rightY = -20); такое
    -- смещение невалидно и НЕ должно участвовать ни в сейвах (шаг 1/2),
    -- ни в промахах с остановкой на лицевой стороне — иначе событийная
    -- физика ловила быстрый мяч прямо на «пустой» ракетке («сейв» при
    -- Y=8.34 против зоны [-20..-16], баги A1/F1b/G1) либо запирала его
    -- шагом 1 на edgeR в отрыве от настоящей позиции (фантомный отскок).
    -- Валидные позиции [1..height-paddleH] работают как раньше; диапазон
    -- ровно тот же, что у движения ракеток выше — иначе «заведённая за
    -- борт» тестом ракетка (leftY = height - paddleH + 1) продолжала бы
    -- участвовать в столкновениях, хотя её движение уже запрещено.
    ------------------------------------------------------------------------
    local function paddleInGame(padY)
        return padY >= 1 and padY <= c.height - c.paddleH
    end

    local bx, by = s.ballX, s.ballY
    local vx, vy = s.vx, s.vy

    -- Защита от нулевой горизонтальной скорости (иначе события по X
    -- недостижимы и кадр вырождается): минимальный |vx|.
    if vx == 0 then vx = 0.05 end

    --- Пересчёт угла/скорости при сейве о ракетку (общий код шагов 1 и 2).
    -- rel = точка попадания (-1 верхний край .. +1 нижний). Калибровка по
    -- тесту B1: «центровой» удар (центр мяча на 0.5 клетки ВЫШЕ центра
    -- ракетки из-за целочисленного floor в тестах) обязан давать почти
    -- плоский отскок, а крайние клетки — максимальный угол. Поэтому знаменатель
    -- нормировки — половина окна попадания плюс полшага (dead-zone), т.е.
    --   denom = (paddleH - ballH)/2 + ballH/2 = paddleH/2:
    --   rel = clamp(((by+ballH/2)-(padY+paddleH/2))/(paddleH/2), -1, +1)
    -- Верхняя клетка окна -> rel=-1 (крутой вверх), нижняя -> +1 (вниз),
    -- центральный удар -> |rel|=0.2 (плоский выстрел, инвариант B1c/B1d).
    -- Модуль вектора после удара строго равен speed (каноника
    -- vx=cos(rel*A)*speed, vy=sin(rel*A)*speed).
    local function bounceOff(padY)
        local rel = clamp(((by + c.ballH / 2) - (padY + c.paddleH / 2))
                          / (c.paddleH / 2), -1, 1)
        local speed = math.sqrt(vx * vx + vy * vy) * c.ballAccel
        local dirOut = (vx < 0) and 1 or -1
        vx = dirOut * math.abs(math.cos(rel * c.maxBounceAngle)) * speed
        -- Направление задаётся знаком rel (он же знак centerDiff): центр мяча
        -- ВЫШЕ центра ракетки -> rel<0 -> vy<0 (вверх), НИЖЕ -> vy>0 (вниз).
        vy = math.sin(rel * c.maxBounceAngle) * speed
        bx = (dirOut > 0) and faceL or faceR
    end

    --- Завершение розыгрыша голом. Направление задаётся ЯВНО (dir): мяч летел
    -- влево (dir=-1) -> отличилась правая сторона (scoreR), и наоборот. Знак
    -- локального vx к моменту вызова может быть уже развёрнут сейвом в том же
    -- кадре, поэтому доверять ему нельзя — только переданному направлению
    -- полёта к линии гола.
    -- Гол фиксируется ЗДЕСЬ (в момент завершения розыгрыша): счёт увеличивается
    -- и ставится запись протокола s.goalPending — ровно одна на гол. dedup по
    -- флагу гарантирует инвариант «одна запись = +1 к одному из счётов»;
    -- popGoal лишь выдаёт запись циклу вызывающего (main.lua/тесты).
    local function finishRound(dir)
        -- Dedup: один розыгрыш = ровно один гол (страховка от повторного
        -- вызова из разных шагов одного кадра).
        if s.goalPending then return end
        if dir < 0 then
            s.scoreR = s.scoreR + 1
            s.state, s.msg = "round", "Right scores!"
        else
            s.scoreL = s.scoreL + 1
            s.state, s.msg = "round", "Left scores!"
        end
        s.goalPending = { scoreL = s.scoreL, scoreR = s.scoreR, msg = s.msg }
        if not s.goalLog then s.goalLog = {} end
        table.insert(s.goalLog, s.goalPending)
        if s.scoreL >= c.winScore or s.scoreR >= c.winScore then
            s.state = "over"
            -- Управление на экране конца матча — SPACE (реванш) / q (выход), см. main.lua
            if s.scoreL >= c.winScore then
                s.msg = "YOU WIN!  [SPACE] again  [q] quit"
            else
                s.msg = "CPU WINS! [SPACE] again  [q] quit"
            end
        end
        s.ballX, s.ballY, s.vx, s.vy = bx, by, vx, vy
    end

    ------------------------------------------------------------------------
    -- ШАГ 0. Гол засчитывается ДИСКРЕТНО и с ПРИОРИТЕТОМ над сейвом: если
    -- мяч уже пересёк линию полного пропуска (goal-событие прошлого кадра
    -- поставило его ровно на линию), розыгрыш завершается ЭТИМ кадром —
    -- возврат встречной ракетки между кадрами запоздал. Направление гола —
    -- знак скорости В МОМЕНТ пересечения: у goalL обязан лететь влево,
    -- у goalR — вправо; встречный знак означает, что за борт мяч ушёл уже
    -- после сейва (сейв ставит bx точно на лицевую сторону, а edge/goal
    -- разделены >2 клетками) — это физически невозможно, но проверка
    -- страхует направление счёта от ложного «не в те ворота» (баг A1).
    ------------------------------------------------------------------------
    if bx <= goalL then
        finishRound(-1)
        return
    elseif bx >= goalR then
        finishRound(1)
        return
    end

    ------------------------------------------------------------------------
    -- ШАГ 1. Мяч стоит на лицевой стороне встречной ракетки (промах был ранее,
    -- но goal ещё не достигнут) — значит ракета была подставлена между кадрами:
    -- сейв (перекрытие по Y в точке касания). Условие «летит К ракетке»
    -- (vx<0 у edgeL / vx>0 у edgeR) отделяет сейв от полёта ОТ лицевой стороны
    -- к воротам: там возврат невозможен и работает шаг 1b.
    -- Если ракетки нет в игре (фильтр paddleInGame) или произошло промахе —
    -- мяч НЕ доматывается к линии гола в том же кадре (старый баг «мгновенного
    -- гола», F1c): он делает честный шаг |vx| наружу; пересечение goal-линии
    -- случится дискретно — шагом 2 (ближайшее событие) или шагом 0 следующим
    -- кадром, когда мяч реально окажется за краем поля.
    ------------------------------------------------------------------------
    if (vx < 0 and bx <= edgeL + EPS) or (vx > 0 and bx >= edgeR - EPS) then
        local padY = (vx < 0) and s.leftY or s.rightY
        if paddleInGame(padY)
           and by + c.ballH - 1 >= padY and by <= padY + c.paddleH - 1 then
            -- Сейв возвращённой ракеткой: угол/скорость по bounceOff, кадр
            -- завершён (мяч уже на нужной стороне лицевой стороны).
            bounceOff(padY)
            s.ballX, s.ballY, s.vx, s.vy = bx, by, vx, vy
            return
        end
        -- Промах / ракетки нет в игре: одно событие за кадр — обычный шаг
        -- полёта наружу из точки касания (без домотки до goal-линии).
    end

    ------------------------------------------------------------------------
    -- ШАГ 1b. Мяч у лицевой стороны, но летит ОТ неё (отскок случился ровно на
    -- edge-линии): гол невозможен — продолжаем честный полёт шагом 2.
    ------------------------------------------------------------------------

    ------------------------------------------------------------------------
    -- ШАГ 2. Полёт до БЛИЖАЙШЕГО события кадра (ровно одно событие):
    --   * «wall» — отскок от верхней/нижней стенки: vy меняет знак, кадр
    --     завершается (никакой домотки — защита от телепорта);
    --   * «edge» — касание лицевой стороны ракетки: сейв (перекрытие по Y
    --     в точке касания) или промах — мяч остаётся ровно на лицевой
    --     стороне и в СЛЕДУЮЩЕМ кадре шаг 1 решит: сейв (ракета вернулась)
    --     или гол (ушла);
    --   * «goal» — пересечение линии полного пропуска. Возможно ТОЛЬКО
    --     когда мяч уже в полости ворот (за лицевой стороной ракетки):
    --     инвариант edge < goal гарантирует, что с поля событие «edge»
    --     всегда ближе — прямого телепорта в гол нет.
    ------------------------------------------------------------------------
    ------------------------------------------------------------------------
    -- СОБЫТИЙНЫЙ ЦИКЛ КАДРА. Честный шаг кадра по X равен |vx|; путь
    -- делится на сегменты до ближайших значимых точек (стенка / лицевая
    -- сторона ракетки / линия гола). Смена знака vy (стенка) НЕ завершает
    -- кадр — остаток шага продолжает цикл, иначе быстрый мяч залипал на
    -- месте (баг H1: X=5, vx=-10.9 вечно). Гол исполняется шагом 0
    -- СЛЕДУЮЩИМ кадром: goal-событие ставит мяч ровно на линию полного
    -- пропуска, и последний кадр «play» имеет мяч ещё перекрывающим край
    -- поля (инварианты F1c/A1). Прямой телепорт в гол с поля невозможен:
    -- инвариант edge < goal гарантирует, что событие «edge» ближе, а из
    -- полости ворот обратного пути к ракетке нет (dEdge не считается).
    -- Направление полёта (знак vx) фиксируется ОДИН раз в начале кадра
    -- (dirNow): сейв меняет s.vx/локальный vx, но события текущего кадра
    -- считаются для прежнего направления — иначе сразу после bounceOff
    -- симметричная edge-линия оказывалась «впереди» и цикл входил в
    -- бесконечную петлю (zалипание X=5 при vx=-10.9).
    ------------------------------------------------------------------------
    local dXTotal = math.abs(vx)   -- честный шаг кадра по X
    local moved   = 0              -- уже пройдено по X в этом кадре

    while true do
        local dxRemain = dXTotal - moved
        if dxRemain <= EPS then break end

        local dirNow = (vx < 0) and -1 or 1

        local dWall
        if vy > EPS then
            dWall = (yBot - by) / vy
        elseif vy < -EPS then
            dWall = (by - yTop) / (-vy)
        else
            dWall = nil
        end

        -- Событие «edge»: только пока мяч на стороне поля И встречная
        -- ракетка в игре (paddleInGame): из полости ворот обратного пути
        -- к ракетке нет; «убранная» тестом ракетка не должна останавливать
        -- мяч на своей лицевой стороне (фантомный сейв/разворот vx, G1/A1).
        -- Достижимость строго «впереди»: bx > edgeL при движении влево —
        -- иначе мяч, уже стоящий точно на линии (bx == edgeL), получал
        -- dEdge = 0 и цикл бесконечно повторял промах без продвижения
        -- (залипание H1: X=5, vx=-10.9). Мяч на лицевой стороне обрабатывает
        -- шаг 1 перед циклом.
        local dEdge
        if dirNow < 0 then
            if bx > edgeL + EPS and paddleInGame(s.leftY) then
                dEdge = (bx - edgeL) / (-vx)
            end
        else
            if bx < edgeR - EPS and paddleInGame(s.rightY) then
                dEdge = (edgeR - bx) / vx
            end
        end

        -- Событие «гол»: цель достижима только если мяч движется К линии.
        local dGoalC
        if dirNow < 0 then
            if bx > goalL then dGoalC = (bx - goalL) / (-vx) end
        else
            if bx < goalR then dGoalC = (goalR - bx) / vx end
        end

        local dX, xKind
        if dEdge ~= nil and (dGoalC == nil or dEdge <= dGoalC) then
            dX, xKind = dEdge, "edge"
        elseif dGoalC ~= nil then
            dX, xKind = dGoalC, "goal"
        else
            dX, xKind = nil, nil
        end

        if dX == nil then
            -- Ни одного события по X впереди — свободный полёт до конца шага.
            bx = bx + vx * dxRemain
            by = advanceY(by, vy * dxRemain)
            break
        end

        if dX > dxRemain + EPS then
            -- Ближайшее событие дальше, чем остаток честного шага: кадр
            -- заканчивается обычным продвижением (гола/сейва не будет).
            bx = bx + vx * dxRemain
            by = advanceY(by, vy * dxRemain)
            break
        end

        if dWall ~= nil and dWall < dX then
            -- Событие кадра — стенка: отражаем vy, продвигаемся до стенки,
            -- остаток шага продолжает цикл (все события исполняются по
            -- порядку достижения — это не «доматывание сквозь»).
            bx = bx + vx * dWall
            by = (dWall * vy > 0) and yBot or yTop
            vy = -vy
            moved = moved + math.abs(vx) * dWall
        elseif xKind == "goal" then
            -- Мяч точно на линии полного пропуска. Розыгрыш завершается
            -- СЛЕДУЮЩИМ кадром шагом 0 — так последний кадр play имеет мяч
            -- ещё перекрывающим край поля (инварианты F1c/A1).
            bx = (dirNow < 0) and goalL or goalR
            by = advanceY(by, vy * dX)
            break
        else
            -- «edge»: касание лицевой стороны встречной ракетки. Перекрытие
            -- по Y проверяется В ТОЧКЕ касания (никаких фантомных отскоков).
            bx = (dirNow < 0) and edgeL or edgeR
            by = advanceY(by, vy * dX)
            moved = moved + math.abs(vx) * dX
            local padY = (dirNow < 0) and s.leftY or s.rightY
            if by + c.ballH - 1 >= padY and by <= padY + c.paddleH - 1 then
                bounceOff(padY)   -- сейв: vx развёрнут, dirOut ведёт в поле
                break
            end
            -- Промах: направление сохраняется (наружу, в полость ворот);
            -- цикл продолжится и доведёт мяч до goal-линии этим же кадром.
        end
    end

    s.ballX, s.ballY = bx, by
    s.vx, s.vy = vx, vy
end

--- Обработка событий раунда/паузы вне физики.
-- now — «часы» вызывающего (main.lua передаёт os.clock()); если не передан,
-- берётся s.lastNow (его обновляет main.lua каждый кадр), и лишь затем os.clock().
-- ВАЖНО: handleRound НЕ должен сбрасывать roundUntil при внешнем переходе
-- round->play (SPACE из меню-подобных состояний) — иначе старые «зависшие»
-- часы roundUntil будут мгновенно ре-сервисить раунд в вечном цикле.
-- Запись протокола гола создаётся в finishRound() (s.goalPending) — здесь
-- остаётся только тайминг паузы и подача.
function M.handleRound(s, now)
    if s.state ~= "round" then return end
    if now == nil then now = s.lastNow or os.clock() end
    if not s.roundStarted then
        -- Первый вход в состояние «round»: фиксируем факт старта паузы.
        s.roundStarted = true
    end
    if not s.roundUntil then
        s.roundUntil = now + 1.2
    end
    if now >= s.roundUntil then
        s.roundUntil   = nil
        s.roundStarted = nil
        local dir = (s.scoreL + s.scoreR) % 2 == 0 and 1 or -1
        -- подача использует тот же детерминированный randFn, что и resetBall выше
        M.resetBall(s, dir)
        s.state = "play"
        s.msg = ""
    end
end

--- Выдать запись о голе, зафиксированном в момент завершения розыгрыша
-- (finishRound ставит s.goalPending). Контракт: ровно одна выдача на гол —
-- запись снимается из состояния, поэтому повторные вызовы во время паузы
-- раунда возвращают nil (dedup по факту, а не по кадру).
function M.popGoal(s)
    local g = s.goalPending
    if g then
        s.goalPending = nil
    end
    return g
end

return M
